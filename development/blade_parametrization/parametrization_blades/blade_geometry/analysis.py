"""Axial-section measurements for reproducible sensitivity studies.

All geometry is generated by build_section. This module only converts units,
assembles plotting arrays, and evaluates sampled diagnostics; no alternative
camberline, thickness, rounding, or relief implementation lives here.
"""
from copy import deepcopy
from pathlib import Path
import numpy as np

from .geometry import build_section, turning_angle, _integral
from .parameters import load_case, resolve_parameters
from .thickness import denton_body


def baseline(family, count=601, parameters=None):
    if parameters is None:
        parameters = resolve_parameters(load_case(Path(__file__).parent / "cases" / f"{family}.yaml")).values
    p = deepcopy(parameters)
    p["numerics"]["number_of_points"] = count
    if p["geometry"]["type"] != "axial":
        raise ValueError("These developed millimetre views require an axial section.")
    section = build_section(p)
    scale = 1000 * p["geometry"]["mean_radius"]
    dense = np.unique(np.r_[np.linspace(0, 1, max(4001, 8*count+1)), section.xi])
    beta = turning_angle(dense, p["camberline"])
    arclength = 1000*section.meridional_chord*_integral(1/np.cos(beta), dense)
    return dict(family=family, parameters=p, section=section, xi=section.xi,
                camber=scale*section.camber, plus=scale*section.plus, minus=scale*section.minus,
                plus_offset=scale*section.thickness["plus_chart_offset"],
                minus_offset=scale*section.thickness["minus_chart_offset"],
                s=np.interp(section.xi, dense, arclength),
                fullness=p["thickness"]["leading_edge_fullness"],
                trailing_fullness=p["thickness"]["trailing_edge_fullness"])


def with_fullness(blade, leading, trailing):
    p = deepcopy(blade["parameters"])
    p["thickness"].update(leading_edge_fullness=leading, trailing_edge_fullness=trailing)
    return baseline(blade["family"], p["numerics"]["number_of_points"], p)


def outline(blade, flattened=False):
    if flattened:
        plus = np.column_stack((blade["s"], blade["plus_offset"]))
        minus = np.column_stack((blade["s"], -blade["minus_offset"]))
    else:
        plus, minus = blade["plus"], blade["minus"]
    return np.vstack((plus, minus[::-1], plus[:1]))


def common_limits(reference, blades):
    curves = [outline(b) for b in [reference, *blades]]
    flat = [outline(b, True) for b in [reference, *blades]]
    xy, uv = np.vstack(curves), np.vstack(flat)
    padding = .06*reference["parameters"]["geometry"]["meridional_chord"]*1000
    span = max(np.ptp(xy[:, 1]), np.ptp(uv[:, 1])) + 2*padding
    center_blade = .5*(xy[:, 1].min()+xy[:, 1].max())
    center_flat = .5*(uv[:, 1].min()+uv[:, 1].max())
    return ((float(min(xy[:, 0].min(), uv[:, 0].min())-padding),
             float(max(xy[:, 0].max(), uv[:, 0].max())+padding)),
            (float(center_blade-span/2), float(center_blade+span/2)),
            (float(center_flat-span/2), float(center_flat+span/2)))


def audit(blade, count=16001):
    """Dense thickness/margin checks; intersections at the plotted resolution.

    build_section raises on a sampled self/neighbor intersection. The dense
    diagnostic section avoids the quadratic cost of repeating that test.
    """
    p = deepcopy(blade["parameters"])
    p["numerics"]["number_of_points"] = count
    dense = build_section(p, check_intersections=False)
    x = np.linspace(0, 1, count)
    body = denton_body(x, p["thickness"])
    slopes = np.diff(body)
    signs = np.sign(slopes[np.abs(slopes) > 1e-12])
    changes = int(np.count_nonzero(np.diff(signs)))
    scale = 1000*dense.meridional_chord
    return dict(family=blade["family"], leading_fullness=blade["fullness"],
                trailing_fullness=blade["trailing_fullness"],
                positive_thickness=bool(np.all(body > 0)),
                thickness_slope_sign_changes=changes,
                maximum_body_thickness_mm=float(scale*body.max()),
                body_peak_xi=float(x[np.argmax(body)]),
                maximum_paired_thickness_mm=dense.diagnostics["actual_maximum_thickness_mm"],
                minimum_normal_map_margin=dense.diagnostics["min_normal_map_margin"],
                self_intersection=False, neighbor_intersection=False,
                intersection_sample_count=len(blade["xi"]),
                diagnostic_sample_count=len(dense.xi))
